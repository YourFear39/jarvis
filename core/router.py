"""
Маршрутизатор запросов — определяет уровень обработки ДО вызова дорогого LLM.

Уровни:
  Level.SEARCH (2) — поиск DuckDuckGo + Groq для структурирования (дёшево, быстро)
  Level.AI     (3) — полный LLM с инструментами (Gemini/Claude, тратит квоту)

Level 1 (локальные команды) обрабатывается отдельно в core/local_handler.py
и вызывается до этого роутера — здесь не рассматривается.

Логика классификации:
  1. Если запрос явно требует AI (заметки, план, код, рассуждение) → Level.AI
  2. Если запрос явно информационный (погода, новости, факты, "что такое") → Level.SEARCH
  3. По умолчанию → Level.SEARCH (безопасный выбор, не тратит Gemini-квоту)
"""

from __future__ import annotations

import re
from enum import IntEnum


class Level(IntEnum):
    SEARCH = 2
    AI = 3


# ---------------------------------------------------------------------------
# Паттерны → Level.AI
# Всё что требует полного LLM: tool calls, сложный анализ, творчество, память
# ---------------------------------------------------------------------------

_AI_PATTERNS: list[str] = [
    # Явные AI-триггеры
    r"с\s+помощью\s+и[ий]",
    r"используй\s+и[ий]",
    r"попроси\s+и[ий]",
    r"через\s+и[ий]",
    r"пусть\s+и[ий]",
    r"попроси\s+искусственный",

    # Рассуждение / анализ
    r"\bподумай\b",
    r"\bобдумай\b",
    r"\bпоразмышляй\b",
    r"\bпроанализируй\b",
    r"\bразбери\s+(?:на|по|это|задачу|код|текст)\b",
    r"\bобъясни\s+(?:мне\s+)?(?:почему|как|зачем)\b",

    # Творчество / генерация
    r"\bпридумай\b",
    r"\bсочини\b",
    r"\bвыдумай\b",
    r"напиши\s+(?:план|код|скрипт|функцию|класс|письмо|текст|эссе|стих|рассказ|историю)",
    r"составь\s+(?:план|описание|инструкцию|алгоритм)",
    r"\bспланируй\b",
    r"разработай\s+(?:план|стратегию|алгоритм|архитектуру)",
    r"помоги\s+(?:написать|придумать|разработать|создать|сделать)",
    r"помоги\s+мне\s+(?:с|написать|придумать)",

    # Управление заметками и задачами (требуют tool calls)
    r"\bзапомни\b",
    r"\bзапиши\b",
    r"добавь\s+(?:заметку|задачу|note|task)",
    r"новую?\s+(?:заметку|задачу)",
    r"создай\s+(?:заметку|задачу)",
    r"покажи\s+(?:заметки|задачи|мои\s+заметки|мои\s+задачи)",
    r"мои\s+(?:заметки|задачи)",
    r"(?:выполни|завершил?|сделал?|отметь)\s+задачу",
    r"удали\s+(?:заметку|задачу)",

    # Управление планами
    r"создай\s+план",
    r"покажи\s+план",
    r"обнови\s+план",

    # Файлы (чтение через LLM-инструмент)
    r"прочитай\s+файл",

    # Память и история разговора
    r"что\s+(?:я\s+)?(?:тебе\s+)?говорил",
    r"(?:вспомни|помнишь)\b",
    r"что\s+ты\s+знаешь\s+обо\s+мне",
]

_AI_RE = re.compile("|".join(_AI_PATTERNS), re.IGNORECASE)

# ---------------------------------------------------------------------------
# Паттерны → гарантированный Level.SEARCH
# Явные информационные запросы, всегда требуют поиска в интернете.
# Даже если они каким-то образом прошли бы в Level.AI — направляем в поиск.
# ---------------------------------------------------------------------------

_SEARCH_PATTERNS: list[str] = [
    # Погода
    r"\bпогода\b",
    r"\bтемпература\b",
    r"\bпрогноз\b",
    r"\bосадки\b",
    r"\bдождь\s+(?:будет|завтра|сегодня)\b",
    r"\bснег\s+(?:будет|завтра|сегодня)\b",

    # Новости / текущие события
    r"\bновости\b",
    r"\bпоследние\s+(?:новости|события|обновления)\b",
    r"\bчто\s+случилось\b",
    r"\bчто\s+нового\b",
    r"\bсейчас\s+(?:происходит|творится)\b",

    # Курсы / цены / финансы
    r"\bкурс\s+(?:валют|доллара|евро|рубля)\b",
    r"\bдоллар\s+(?:сегодня|сейчас)\b",
    r"\bбиткоин\s+(?:цена|курс|сейчас)\b",
    r"\bцена\s+(?:на|акций|нефти)\b",
    r"\bсколько\s+стоит\b",

    # Факты / справка
    r"\bчто\s+такое\b",
    r"\bкто\s+такой\b",
    r"\bкто\s+такая\b",
    r"\bгде\s+находится\b",
    r"\bкогда\s+(?:был|была|было|были|открыл|открыли|основан|основали|создал|создали|родился|умер|изобрел|изобрели|закончилась|закончился|закончилось|началась|началось|произошло|произошла|полетел|полетела|полетели|запустил|запустили|высадил|приземлил)\b",
    r"\bсколько\s+(?:лет|метров|километров|человек|населен)\b",
    r"\bкак\s+далеко\b",
    r"\bкакова\s+(?:столица|площадь|население)\b",
    r"\bстолица\s+\w+\b",

    # Информационные вопросы ("расскажи о X", "как работает X", "почему X")
    r"\bрасскажи\s+(?:о|об|про)\b",
    r"\bкак\s+(?:работает|устроен|устроена|работают|устроены)\b",
    r"\bкак\s+установить\b",
    r"\bпочему\b",
    r"\bчто\s+лучше\b",
    r"\bчем\s+отличается\b",
    r"\bв\s+чём\s+разница\b",
    r"\bкак(?:ой|ая|ое|ие)\s+самы[йяео]\b",
    r"\bсамы[йяео]\s+(?:высокий|низкий|большой|маленький|длинный|короткий|быстрый|медленный|старый|новый|дорогой|дешёвый|сильный|слабый)\b",
    r"\bсамая\s+(?:длинная|большая|маленькая|короткая|высокая|низкая|быстрая|медленная|старая|новая|дорогая|дешёвая|сильная|слабая)\b",
    r"\bкто\s+(?:изобрёл|изобрел|придумал|написал|создал|основал|открыл)\b",
    r"\bкто\s+написал\b",

    # Явный поиск
    r"\bнайди\s+(?:в\s+интернете|информацию|данные)\b",
    r"\bпоищи\b",
    r"\bпогугли\b",
    r"\bищи\b",
]

_SEARCH_RE = re.compile("|".join(_SEARCH_PATTERNS), re.IGNORECASE)


def classify(message: str) -> Level:
    """
    Определяет уровень обработки запроса.

    Level.AI     — сложная задача, создание контента, управление заметками/задачами (по умолчанию)
    Level.SEARCH — явный информационный вопрос: погода, новости, факты, курсы
    """
    # AI-паттерны проверяем ПЕРВЫМИ: "найди и запомни" должно идти в LLM, а не в поиск
    if _AI_RE.search(message):
        return Level.AI

    # Явные информационные запросы — поиск в интернете
    if _SEARCH_RE.search(message):
        return Level.SEARCH

    # По умолчанию — AI: разговорные фразы ("привет", "расскажи о себе") должны идти в LLM
    return Level.AI
